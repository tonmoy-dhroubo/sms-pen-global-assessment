import { createHash, randomUUID } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import fs from "node:fs/promises";
import path from "node:path";
import { Readable, Transform } from "node:stream";
import { pipeline } from "node:stream/promises";
import type { ReadableStream as WebReadableStream } from "node:stream/web";
import {
  ObjectChangedError,
  ObjectNotFoundError,
  isPendingKey,
  type ObjectInfo,
  type PresignedDownload,
  type PresignedUpload,
  type Storage,
} from "./storage-core";
import { signToken } from "./storage-token";

// The filesystem storage adapter (D-045): the same `Storage` interface as the S3 one, over a directory on disk, so the
// app runs with nothing but Node and PostgreSQL. No `server-only` and no environment access (the directory and the
// signing secret are passed in), so it can be tested and used by the command-line scripts. See `storage-core.ts`
// for the contract; this file documents only what differs.
//
// Layout under the root directory:
//   <key>                   the object (same keys as S3: `pending/...`, `submissions/...`)
//   .meta/<key>.json        its content type (S3 keeps this as object metadata)
//   <dir>/.tmp-<uuid>       a file being written; renamed into place when complete, so a reader never sees half a file
//   .sms-storage            marks the directory as ours, so `deletePrefix("")` can never empty some other folder
// Keys never contain a segment starting with "." (they are generated by the server, and checked here as well), so
// none of the bookkeeping names above can collide with, or be reached through, a key.

const MARKER = ".sms-storage";
const META_DIR = ".meta";
const URL_BASE = "/api/uploads";

export interface FilesystemStorageConfig {
  /** The storage directory (created on first use). */
  rootDir: string;
  /** Signs upload and download URLs (SESSION_SECRET). */
  secret: string;
  /** Where the app serves the signed URLs. */
  urlBase?: string;
}

/** Thrown by `storeUpload` when what arrived is not what the URL was issued for (wrong length, cut off). */
export class UploadRejectedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "UploadRejectedError";
  }
}

export interface FilesystemStorage extends Storage {
  readonly rootDir: string;
  /**
   * Writes an incoming upload to `key`: streamed to a temporary file next to it, checked against `expectedLength`, then
   * renamed into place. Throws `UploadRejectedError` (and leaves nothing behind) if the body is not exactly that long.
   */
  storeUpload(
    key: string,
    contentType: string,
    expectedLength: number,
    body: ReadableStream<Uint8Array> | null,
  ): Promise<ObjectInfo>;
  /** The object and a stream of it, or `null` if it does not exist. */
  openObject(key: string): Promise<{ info: ObjectInfo; stream: Readable } | null>;
}

// --- Keys and paths ----------------------------------------------------------------------------------------------

// Control characters, backslash and the characters Windows reserves (`:` would also open an alternate data stream).
const UNSAFE_SEGMENT = /[\u0000-\u001f\u007f\\:<>"|?*]/;

/** Whether `key` is a name this adapter will touch (see `assertSafeKey`). */
export function isSafeKey(key: string): boolean {
  try {
    assertSafeKey(key);
    return true;
  } catch {
    return false;
  }
}

/** Throws unless every segment of `key` is an ordinary name: no `.`/`..`/hidden names, separators or reserved characters. */
function assertSafeKey(key: string): void {
  const segments = key.split("/");
  if (
    key === "" ||
    segments.some((s) => s === "" || s.startsWith(".") || UNSAFE_SEGMENT.test(s) || s.length > 255)
  ) {
    throw new TypeError(`Invalid storage key: ${JSON.stringify(key)}`);
  }
}

function isMissing(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | undefined)?.code;
  return code === "ENOENT" || code === "ENOTDIR" || code === "EISDIR";
}

async function rename(from: string, to: string): Promise<void> {
  // Windows refuses to replace a file another process has open for an instant (EPERM/EBUSY); a few retries ride it out.
  for (let attempt = 0; ; attempt += 1) {
    try {
      await fs.rename(from, to);
      return;
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (attempt >= 5 || (code !== "EPERM" && code !== "EBUSY" && code !== "EACCES")) throw error;
      await new Promise((resolve) => setTimeout(resolve, 20 * (attempt + 1)));
    }
  }
}

function assertExpiry(expiresIn: number): void {
  if (!Number.isInteger(expiresIn) || expiresIn < 1) {
    throw new RangeError("expiresIn must be a whole number of seconds, at least 1");
  }
}

export function createFilesystemStorage(config: FilesystemStorageConfig): FilesystemStorage {
  const root = path.resolve(config.rootDir);
  const urlBase = config.urlBase ?? URL_BASE;
  let rootReady = false;

  const dataPath = (key: string): string => {
    assertSafeKey(key);
    const target = path.resolve(root, ...key.split("/"));
    // Belt and braces: the key check above already rules out `..`; this proves the result is inside the root.
    if (!target.startsWith(root + path.sep)) throw new TypeError(`Invalid storage key: ${key}`);
    return target;
  };
  const metaPath = (key: string): string =>
    `${path.join(root, META_DIR, path.relative(root, dataPath(key)))}.json`;

  /** Creates the directory if needed and refuses one that is non-empty and not ours (so we never delete someone's files). */
  async function ensureRoot(): Promise<void> {
    if (rootReady) return;
    await fs.mkdir(root, { recursive: true });
    const entries = await fs.readdir(root);
    if (!entries.includes(MARKER)) {
      if (entries.length > 0) {
        throw new Error(
          `${root} is not empty and was not created by this app, so it cannot be used as FILE_STORAGE_DIR. ` +
            "Point FILE_STORAGE_DIR at an empty or new directory.",
        );
      }
      await fs.writeFile(path.join(root, MARKER), "Managed by the Student Management System.\n");
    }
    rootReady = true;
  }

  async function info(key: string): Promise<ObjectInfo | null> {
    let stat;
    try {
      stat = await fs.stat(dataPath(key), { bigint: true });
    } catch (error) {
      if (isMissing(error)) return null;
      throw error;
    }
    if (!stat.isFile()) return null;
    let contentType: string | null = null;
    try {
      const meta = JSON.parse(await fs.readFile(metaPath(key), "utf8")) as {
        contentType?: unknown;
      };
      if (typeof meta.contentType === "string") contentType = meta.contentType;
    } catch {
      /* no metadata: the type is unknown */
    }
    return {
      sizeBytes: Number(stat.size),
      contentType,
      lastModified: new Date(Number(stat.mtimeNs / BigInt(1_000_000))),
      // Changes whenever the object is replaced (a new file has a new inode and mtime): size, mtime in ns, inode.
      etag: `"${stat.size.toString(16)}-${stat.mtimeNs.toString(16)}-${stat.ino.toString(16)}"`,
    };
  }

  async function writeMeta(key: string, contentType: string): Promise<void> {
    const file = metaPath(key);
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, JSON.stringify({ contentType }));
  }

  async function tempFileFor(key: string): Promise<string> {
    const target = dataPath(key);
    await ensureRoot();
    await fs.mkdir(path.dirname(target), { recursive: true });
    return path.join(path.dirname(target), `.tmp-${randomUUID()}`);
  }

  /** Every object key under `prefix` (a plain string prefix, like S3's), skipping bookkeeping names. */
  async function listKeys(prefix: string): Promise<string[]> {
    const dirPart = prefix.slice(0, prefix.lastIndexOf("/") + 1);
    const keys: string[] = [];
    const walk = async (dir: string, relative: string): Promise<void> => {
      let entries;
      try {
        entries = await fs.readdir(dir, { withFileTypes: true });
      } catch (error) {
        if (isMissing(error)) return;
        throw error;
      }
      for (const entry of entries) {
        if (entry.name.startsWith(".")) continue;
        const key = `${relative}${entry.name}`;
        if (entry.isDirectory()) await walk(path.join(dir, entry.name), `${key}/`);
        else if (entry.isFile() && key.startsWith(prefix)) keys.push(key);
      }
    };
    await walk(
      dirPart === "" ? root : path.join(root, ...dirPart.slice(0, -1).split("/")),
      dirPart,
    );
    return keys;
  }

  /** Removes `dir` and its parents while they are empty, never going above `stop`. */
  async function pruneEmpty(dir: string, stop: string): Promise<void> {
    for (let current = dir; current.startsWith(stop + path.sep); current = path.dirname(current)) {
      try {
        await fs.rmdir(current);
      } catch {
        return; // not empty (or gone): stop climbing
      }
    }
  }

  const storage: FilesystemStorage = {
    bucket: root,
    rootDir: root,

    async presignPut(key, contentType, sizeBytes, expiresIn): Promise<PresignedUpload> {
      assertExpiry(expiresIn);
      if (!Number.isInteger(sizeBytes) || sizeBytes < 0) {
        throw new RangeError("sizeBytes must be a non-negative whole number");
      }
      assertSafeKey(key);
      // A browser may only ever write to the staging area; confirmed files are written by the server alone (D-042).
      if (!isPendingKey(key)) {
        throw new TypeError(`Upload URLs are only issued for pending keys, got "${key}"`);
      }
      const expiresAt = new Date(Date.now() + expiresIn * 1000);
      const token = signToken(
        { typ: "put", key, ct: contentType, len: sizeBytes, exp: expiresAt.getTime() },
        config.secret,
      );
      return { url: `${urlBase}/${token}`, headers: { "Content-Type": contentType }, expiresAt };
    },

    async presignGet(key, downloadName, expiresIn): Promise<PresignedDownload> {
      assertExpiry(expiresIn);
      assertSafeKey(key);
      const expiresAt = new Date(Date.now() + expiresIn * 1000);
      const token = signToken(
        { typ: "get", key, name: downloadName, exp: expiresAt.getTime() },
        config.secret,
      );
      return { url: `${urlBase}/${token}`, expiresAt };
    },

    headObject: (key) => info(key),

    async copyObject(sourceKey, destinationKey, options = {}) {
      const source = dataPath(sourceKey);
      const before = await info(sourceKey);
      if (!before) throw new ObjectNotFoundError(sourceKey);
      if (options.ifMatch && before.etag !== options.ifMatch) {
        throw new ObjectChangedError(sourceKey);
      }

      const temp = await tempFileFor(destinationKey);
      try {
        try {
          await fs.copyFile(source, temp);
        } catch (error) {
          if (isMissing(error)) throw new ObjectNotFoundError(sourceKey);
          throw error;
        }
        // A replacement (always a new file, see `storeUpload`) between the first look and now would leave a copy of
        // one version labelled with the identity of another: refuse, exactly like S3's conditional copy.
        const after = await info(sourceKey);
        if (!after || after.etag !== before.etag) throw new ObjectChangedError(sourceKey);
        await writeMeta(destinationKey, before.contentType ?? "application/octet-stream");
        await rename(temp, dataPath(destinationKey));
      } catch (error) {
        await fs.rm(temp, { force: true });
        throw error;
      }
      const copy = await info(destinationKey);
      return { etag: copy?.etag ?? null, lastModified: copy?.lastModified ?? new Date() };
    },

    async readRange(key, offset, length) {
      if (!Number.isInteger(offset) || offset < 0) {
        throw new RangeError("offset must be a non-negative whole number");
      }
      if (!Number.isInteger(length) || length < 1) {
        throw new RangeError("length must be a positive whole number");
      }
      let handle;
      try {
        handle = await fs.open(dataPath(key), "r");
      } catch (error) {
        if (isMissing(error)) throw new ObjectNotFoundError(key);
        throw error;
      }
      try {
        const buffer = Buffer.alloc(length);
        const { bytesRead } = await handle.read(buffer, 0, length, offset);
        return buffer.subarray(0, bytesRead);
      } catch (error) {
        if (isMissing(error)) throw new ObjectNotFoundError(key);
        throw error;
      } finally {
        await handle.close();
      }
    },

    async readFirstBytes(key, n) {
      if (!Number.isInteger(n) || n < 1) throw new RangeError("n must be a positive whole number");
      return storage.readRange(key, 0, n);
    },

    async sha256(key) {
      const hash = createHash("sha256");
      try {
        for await (const chunk of createReadStream(dataPath(key))) hash.update(chunk as Buffer);
      } catch (error) {
        if (isMissing(error)) throw new ObjectNotFoundError(key);
        throw error;
      }
      return hash.digest("hex");
    },

    async putObject(key, body, contentType) {
      const temp = await tempFileFor(key);
      try {
        await fs.writeFile(temp, body);
        await writeMeta(key, contentType);
        await rename(temp, dataPath(key));
      } catch (error) {
        await fs.rm(temp, { force: true });
        throw error;
      }
    },

    async deleteObject(key) {
      await fs.rm(dataPath(key), { force: true });
      await fs.rm(metaPath(key), { force: true });
    },

    async deletePrefix(prefix) {
      if (prefix !== "") {
        // Same rules as a key, except it may end in "/" or stop partway through a name.
        assertSafeKey(prefix.endsWith("/") ? prefix.slice(0, -1) : prefix);
      }
      try {
        await fs.access(root);
      } catch {
        return 0; // nothing has ever been stored
      }
      await ensureRoot();
      const keys = await listKeys(prefix);
      for (const key of keys) {
        await fs.rm(dataPath(key), { force: true });
        await fs.rm(metaPath(key), { force: true });
        await pruneEmpty(path.dirname(dataPath(key)), root);
        await pruneEmpty(path.dirname(metaPath(key)), root);
      }
      return keys.length;
    },

    async ensureBucket() {
      await ensureRoot();
    },

    async checkBucket() {
      await ensureRoot();
      const probe = path.join(root, `.health-${randomUUID()}`);
      await fs.writeFile(probe, "ok");
      await fs.rm(probe, { force: true });
    },

    async storeUpload(key, contentType, expectedLength, body) {
      const temp = await tempFileFor(key);
      let received = 0;
      const counter = new Transform({
        transform(chunk: Buffer, _encoding, callback) {
          received += chunk.length;
          // Stop reading as soon as it is too long; there is no need to take the rest.
          if (received > expectedLength) {
            callback(new UploadRejectedError("The file is larger than the size declared for it."));
          } else callback(null, chunk);
        },
      });
      try {
        await pipeline(
          // The DOM and Node typings of a web stream differ only in name; it is the same object.
          body ? Readable.fromWeb(body as WebReadableStream<Uint8Array>) : Readable.from([]),
          counter,
          createWriteStream(temp),
        );
        if (received !== expectedLength) {
          throw new UploadRejectedError("The file is smaller than the size declared for it.");
        }
        await writeMeta(key, contentType);
        await rename(temp, dataPath(key));
      } catch (error) {
        await fs.rm(temp, { force: true });
        if (error instanceof UploadRejectedError) throw error;
        // A browser that closes the connection mid-upload surfaces as an aborted or prematurely closed stream.
        const code = (error as NodeJS.ErrnoException).code;
        if (code === "ERR_STREAM_PREMATURE_CLOSE" || (error as Error).name === "AbortError") {
          throw new UploadRejectedError("The upload was interrupted.");
        }
        throw error;
      }
      const stored = await info(key);
      if (!stored) throw new Error(`Upload vanished after it was stored: ${key}`);
      return stored;
    },

    async openObject(key) {
      const found = await info(key);
      if (!found) return null;
      return { info: found, stream: createReadStream(dataPath(key)) };
    },
  };
  return storage;
}
